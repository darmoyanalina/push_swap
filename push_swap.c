#include "push_swap.h"

int	main(int argc, char **argv)
{
	t_stack	*a;
	t_stack	*b;

	if (argc < 2)
		return (0);
	a = parse(&argv[1]);
	b = NULL;
	insertion_sort(&a, &b);

	return (0);
}
